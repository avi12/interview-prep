import type { PGlite } from "@electric-sql/pglite";
import { openSchemaDb, SqlState, tryStatement } from "#kit/schema.ts";
import { beforeEach, describe, expect, it } from "vitest";

type Person = {
  name?: string | null;
  email?: string;
};
type Course = {
  title?: string | null;
  credits?: number | null;
};

let db: PGlite;
let studentCount = 0;

beforeEach(async () => {
  db = await openSchemaDb({
    testUrl: import.meta.url,
    file: "schema.sql"
  });
  studentCount = 0;
});

function insertStudent({ name = "Dana", email = "dana@example.com" }: Person = {}) {
  return tryStatement({
    db,
    sql: "INSERT INTO students (name, email) VALUES ($1, $2)",
    params: [name, email]
  });
}

function insertCourse({ title = "Databases", credits = 4 }: Course = {}) {
  return tryStatement({
    db,
    sql: "INSERT INTO courses (title, credits) VALUES ($1, $2)",
    params: [title, credits]
  });
}

function enroll({ studentId, courseId, grade = null }: {
  studentId: number;
  courseId: number;
  grade?: number | null;
}) {
  return tryStatement({
    db,
    sql: "INSERT INTO enrollments (student_id, course_id, grade) VALUES ($1, $2, $3)",
    params: [studentId, courseId, grade]
  });
}

async function newStudent() {
  studentCount += 1;
  const { rows } = await db.query<{ id: number }>("INSERT INTO students (name, email) VALUES ($1, $2) RETURNING id", [
    `Student ${studentCount}`,
    `student${studentCount}@example.com`
  ]);
  return rows[0].id;
}

async function newCourse(course: Course = {}) {
  const { rows } = await db.query<{ id: number }>("INSERT INTO courses (title, credits) VALUES ($1, $2) RETURNING id", [course.title ?? "Databases", course.credits ?? 4]);
  return rows[0].id;
}

async function countOf(table: string) {
  const { rows } = await db.query<{ total: number }>(`SELECT COUNT(*)::int AS total FROM ${table}`);
  return rows[0].total;
}

function expectRefused({ result, code }: {
  result: Awaited<ReturnType<typeof tryStatement>>;
  code: string | string[];
}) {
  expect(result.isOk, "the database accepted a row it should have refused").toBe(false);
  expect([code].flat()).toContain(result.code);
}

describe("valid data", () => {
  it("accepts students, courses and enrollments, with ids generated by the database", async () => {
    const student = await insertStudent();
    const course = await insertCourse();
    expect(student.message).toBe("");
    expect(course.message).toBe("");
    const studentId = await newStudent();
    const courseId = await newCourse();
    const result = await enroll({
      studentId,
      courseId,
      grade: 90
    });
    expect(result.message).toBe("");
  });

  it("lets one student take many courses and one course have many students", async () => {
    const students = [await newStudent(), await newStudent()];
    const courses = [await newCourse(), await newCourse({
      title: "Networks",
      credits: 3
    })];
    for (const studentId of students) {
      for (const courseId of courses) {
        expect(
          (await enroll({
            studentId,
            courseId
          })).message
        ).toBe("");
      }
    }
    expect(await countOf("enrollments")).toBe(4);
  });
});

describe("students", () => {
  it("requires a name", async () => {
    expectRefused({
      result: await insertStudent({ name: null }),
      code: SqlState.notNull
    });
  });

  it("requires a unique email", async () => {
    await insertStudent({ email: "same@example.com" });
    expectRefused({
      result: await insertStudent({
        name: "Omer",
        email: "same@example.com"
      }),
      code: SqlState.unique
    });
  });
});

describe("courses", () => {
  it("requires a title", async () => {
    expectRefused({
      result: await insertCourse({ title: null }),
      code: SqlState.notNull
    });
  });

  it("requires credits", async () => {
    expectRefused({
      result: await insertCourse({ credits: null }),
      code: SqlState.notNull
    });
  });

  it("allows credits from 1 to 10 and refuses 0, 11 and negatives", async () => {
    expect((await insertCourse({ credits: 1 })).message).toBe("");
    expect((await insertCourse({ credits: 10 })).message).toBe("");
    for (const credits of [0, 11, -3]) {
      expectRefused({
        result: await insertCourse({ credits }),
        code: SqlState.check
      });
    }
  });
});

describe("enrollments", () => {
  it("refuses an unknown student or an unknown course", async () => {
    const studentId = await newStudent();
    const courseId = await newCourse();
    const unknownId = 9999;
    expectRefused({
      result: await enroll({
        studentId: unknownId,
        courseId
      }),
      code: SqlState.foreignKey
    });
    expectRefused({
      result: await enroll({
        studentId,
        courseId: unknownId
      }),
      code: SqlState.foreignKey
    });
  });

  it("refuses the same student in the same course twice", async () => {
    const studentId = await newStudent();
    const courseId = await newCourse();
    await enroll({
      studentId,
      courseId
    });
    expectRefused({
      result: await enroll({
        studentId,
        courseId,
        grade: 80
      }),
      code: SqlState.unique
    });
  });

  it("allows a grade from 0 to 100 or NULL, and refuses anything else", async () => {
    const studentId = await newStudent();
    for (const grade of [null, 0, 100]) {
      const courseId = await newCourse();
      expect(
        (await enroll({
          studentId,
          courseId,
          grade
        })).message
      ).toBe("");
    }
    for (const grade of [101, -1]) {
      const courseId = await newCourse();
      expectRefused({
        result: await enroll({
          studentId,
          courseId,
          grade
        }),
        code: SqlState.check
      });
    }
  });
});

describe("deleting", () => {
  it("deletes a student's enrollments together with the student", async () => {
    const leavingId = await newStudent();
    const stayingId = await newStudent();
    const courseId = await newCourse();
    await enroll({
      studentId: leavingId,
      courseId
    });
    await enroll({
      studentId: stayingId,
      courseId
    });
    const result = await tryStatement({
      db,
      sql: "DELETE FROM students WHERE id = $1",
      params: [leavingId]
    });
    expect(result.message).toBe("");
    expect(await countOf("enrollments")).toBe(1);
  });

  it("refuses to delete a course that still has enrollments", async () => {
    const studentId = await newStudent();
    const courseId = await newCourse();
    await enroll({
      studentId,
      courseId
    });
    const result = await tryStatement({
      db,
      sql: "DELETE FROM courses WHERE id = $1",
      params: [courseId]
    });
    expectRefused({
      result,
      code: [SqlState.restrict, SqlState.foreignKey]
    });
    expect(await countOf("enrollments")).toBe(1);
  });

  it("deletes a course nobody is enrolled in", async () => {
    const courseId = await newCourse();
    const result = await tryStatement({
      db,
      sql: "DELETE FROM courses WHERE id = $1",
      params: [courseId]
    });
    expect(result.message).toBe("");
  });
});
